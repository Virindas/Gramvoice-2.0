const targets = [
  { lang: 'en', files: ['web/src/i18n/translations/en.ts', 'mobile/i18n/translations/en.ts'] },
  { lang: 'hi', files: ['web/src/i18n/translations/hi.ts', 'mobile/i18n/translations/hi.ts'] },
  { lang: 'ta', files: ['web/src/i18n/translations/ta.ts', 'mobile/i18n/translations/ta.ts'] },
];

for (const target of targets) {
  const dict = newTranslations[target.lang];
  for (const filePath of target.files) {
    if (!fs.existsSync(filePath)) {
      console.warn(`File missing: ${filePath}`);
      continue;
    }
    let content = fs.readFileSync(filePath, 'utf8');
    // Find the last closing brace
    const lastBraceIndex = content.lastIndexOf('};');
    if (lastBraceIndex === -1) {
      console.warn(`Could not find '};' in ${filePath}`);
      continue;
    }

    let appendLines = '\n  // --- Admin & Extended Translations ---\n';
    for (const [k, v] of Object.entries(dict)) {
      // check if key already present in content
      const regex = new RegExp(`["']${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}["']\\s*:`);
      if (!regex.test(content)) {
        appendLines += `  "${k}": "${v.replace(/"/g, '\\"')}",\n`;
      }
    }

    const updated = content.slice(0, lastBraceIndex) + appendLines + content.slice(lastBraceIndex);
    fs.writeFileSync(filePath, updated, 'utf8');
    console.log(`Updated ${filePath} with new translations for ${target.lang}`);
  }
}
